let currentLocale = "ru";
export function setLocale(locale) { currentLocale = ["ru", "en", "zh"].includes(locale) ? locale : "ru"; }
export function getLocale() { return currentLocale; }
export function intlLocale() { return { ru: "ru-RU", en: "en-US", zh: "zh-CN" }[currentLocale]; }
export function t(source, values = {}) {
  const template = currentLocale === "ru" ? source : translations[source]?.[currentLocale === "en" ? 0 : 1] ?? source;
  return template.replace(/\{(\w+)\}/g, (_match, key) => String(values[key] ?? ""));
}

export function localizeDocument(root = document) {
  root.documentElement.lang = currentLocale === "zh" ? "zh-CN" : currentLocale;
  const walker = root.createTreeWalker(root.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const value = node.nodeValue;
    const source = value.trim();
    if (translations[source]) node.nodeValue = value.replace(source, t(source));
  }
  for (const element of root.querySelectorAll("[aria-label], [placeholder], [title]")) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      const value = element.getAttribute(attribute);
      if (value && translations[value]) element.setAttribute(attribute, t(value));
    }
  }
  root.title = "TiM";
}
